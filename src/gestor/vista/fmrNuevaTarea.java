    // Método para llenar el JComboBox de Colaboradores
    private void cargarColaboradores() {
        UsuarioControlador controller = new UsuarioControlador();
        List<Usuario> colaboradores = controller.getListaDeColaboradores();
        
        cmbAsignarA.removeAllItems();
        mapaColaboradores.clear();
        
        cmbAsignarA.addItem("Seleccionar Colaborador"); // <-- ¡AÑADE ESTA LÍNEA!
        
        for (Usuario u : colaboradores) {
            String textoMostrar = u.getNombreCompleto() + " (" + u.getEmail() + ")";
            cmbAsignarA.addItem(textoMostrar);
            mapaColaboradores.put(textoMostrar, u.getIdUsuario());
        }
    }
    
    // Método para llenar los otros JComboBox
