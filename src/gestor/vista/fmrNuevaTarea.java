    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // 1. Obtener los datos del formulario
        String titulo = txtTitulo.getText();
        String descripcion = txtDescripcion.getText();
        String prioridad = cmbPrioridad.getSelectedItem().toString();
        String estado = cmbEstado.getSelectedItem().toString();
        String nombreColaborador = cmbAsignarA.getSelectedItem().toString();
        
        
        
        // A. Validar campos de texto vacíos
        if (titulo.isBlank() || descripcion.isBlank()) {
            JOptionPane.showMessageDialog(this, "Por favor, completa los campos 'Título' y 'Descripción'.", "Campos Vacíos", JOptionPane.WARNING_MESSAGE);
            return; // Detiene la ejecución aquí
        }

        // B. Validar los JComboBox
        if (prioridad.startsWith("Seleccionar") || estado.startsWith("Seleccionar") || nombreColaborador.startsWith("Seleccionar")) {
            JOptionPane.showMessageDialog(this, "Por favor, selecciona una Prioridad, Estado y Colaborador válidos.", "Error de validación", JOptionPane.ERROR_MESSAGE);
            return; // Detiene la ejecución
        }
        
        
        
        
        int idColaborador = mapaColaboradores.get(nombreColaborador); // Busca el ID en el mapa

        // Llamar al controlador
        TareaControlador controller = new TareaControlador();
        boolean exito = controller.crearTarea(
                idColaborador,  // id_asigando
                this.idAdmin,   // id_asignador 
                titulo,
                descripcion,
                estado,
                prioridad
        );

        if (exito) {
            JOptionPane.showMessageDialog(this, "Tarea creada con éxito.");
            this.dispose(); // Cierra ventana
        } else {
            JOptionPane.showMessageDialog(this, "Error al crear la tarea.");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

  
    
              
