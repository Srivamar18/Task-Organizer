    private void btnCompletarTareaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompletarTareaActionPerformed
       // Obtener la fila que el usuario seleccionó
        int filaSeleccionada = tblTareas.getSelectedRow();
        
        //Verificar si el usuario realmente seleccionó una fila
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, selecciona una tarea de la tabla para completarla.", "Ninguna tarea seleccionada", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Obtener el ID de la tarea 
        int idTarea = (int) tblTareas.getValueAt(filaSeleccionada, 0);
        
        // Pedir confirmación
        int confirmacion = JOptionPane.showConfirmDialog(this, 
                "¿Estás seguro de que quieres marcar esta tarea como completada?\nSe eliminará de tu lista.", 
                "Confirmar acción", 
                JOptionPane.YES_NO_OPTION);
        
        // Si el usuario hace clic en Sí
        if (confirmacion == JOptionPane.YES_OPTION) {
            
            // Llama al controlador para eliminar la tarea
            TareaControlador controller = new TareaControlador();
            boolean exito = controller.eliminarTarea(idTarea);
            
            // Informar el resultado y REFESCAR LA TABLA
            if (exito) {
                JOptionPane.showMessageDialog(this, "¡Tarea completada con éxito!");
                cargarTablaTareas(); // ¡Refresca la tabla!
            } else {
                JOptionPane.showMessageDialog(this, "Error al completar la tarea.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnCompletarTareaActionPerformed

