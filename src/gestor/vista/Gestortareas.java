    //Método para Cargar Tabla
    /**
     * Carga la tabla de tareas (tblTareas) basándose en el ROL del usuario guardado.
     */
    private void cargarTablaTareas() {
        DefaultTableModel modeloTabla = (DefaultTableModel) tblTareas.getModel();
        modeloTabla.setRowCount(0); // Limpia la tabla antes de cargar
        
        TareaControlador controller = new TareaControlador();
        List<Tarea> listaTareas;

        // Lógica de Roles
        if (this.usuarioActual.getRol().equals("ADMINISTRADOR")) {
            listaTareas = controller.getListaDeTareas(); 
        } else {
            listaTareas = controller.getListaDeTareasPorUsuario(this.usuarioActual.getIdUsuario());
        }
        
        // Itera y llena la tabla
        for (Tarea tarea : listaTareas) {
            Object[] fila = {
                tarea.getIdTarea(),
                tarea.getTitulo(),
                tarea.getDescripcion(),
                tarea.getEstado(),
                tarea.getPrioridad(),
                tarea.getNombreResponsable(), // Colaborador (Responsable)
                tarea.getNombreAsignador()    // Admin (Asignado por)
            };
            modeloTabla.addRow(fila);
        }
    }
    
    //Método de Roles
    /**
     * Oculta o muestra botones según el rol del usuario.
     */
    private void configurarVistaPorRol() {
        if (this.usuarioActual.getRol().trim().equalsIgnoreCase("ADMINISTRADOR")) {
            btnNuevaTarea.setVisible(true);
            btnCompletarTarea.setVisible(false); // El Admin no "completa" tareas
        } else {
            // El Colaborador puede completar tareas, pero no crear nuevas
            btnNuevaTarea.setVisible(false);
            btnCompletarTarea.setVisible(true);
        }
    }

