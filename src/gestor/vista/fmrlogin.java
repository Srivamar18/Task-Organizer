    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    try {
        
        String email = txtusu.getText();
        
        
        String password = new String(txtcontra.getPassword()); 
        
        
        System.out.println("Intentando iniciar sesión con Email: [" + email + "]");

        
        gestor.controlador.UsuarioControlador controller = new gestor.controlador.UsuarioControlador();
        gestor.modelo.Usuario usuarioLogueado = controller.validarLogin(email, password);

        
        if (usuarioLogueado != null) {
            // ¡Login exitoso!
            System.out.println("Login EXITOSO para: " + usuarioLogueado.getNombreCompleto());
            
            
            Gestortareas dashboard = new Gestortareas(usuarioLogueado);
            dashboard.setVisible(true);
            
            
            javax.swing.JFrame ventanaActual = (javax.swing.JFrame) javax.swing.SwingUtilities.getWindowAncestor(this);
            ventanaActual.dispose();

        } else {
            
            System.out.println("Login FALLIDO: Email o contraseña incorrectos.");
            JOptionPane.showMessageDialog(this, "Email o contraseña incorrectos.", "Error de Login", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    
    } catch (Exception e) {
        
        System.err.println("Error inesperado durante el login: " + e.getMessage());
        e.printStackTrace(); // Imprime el error completo en la consola
        JOptionPane.showMessageDialog(this, "Ocurrió un error inesperado: " + e.getMessage(), "Error Crítico", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton1ActionPerformed


