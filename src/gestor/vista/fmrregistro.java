    private void RegistrousuariosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RegistrousuariosActionPerformed
    // --- 1. Obtener los datos ---
        String nombre = txtnombre2.getText();
        String apellido = txtapellido.getText();
        String email = txtemail.getText();
        String password = new String(txtcontra.getPassword()); // Asumiendo que es JPasswordField
        String rol = combo.getSelectedItem().toString();     

        
        
        if (nombre.isBlank() || apellido.isBlank() || email.isBlank() || password.isBlank()) {
            JOptionPane.showMessageDialog(this, "Por favor, completa todos los campos.", "Campos Vacíos", JOptionPane.WARNING_MESSAGE);
            return; // Detiene la ejecución aquí
        }
        
        
        if (rol.equals("Seleccionar")) {
            JOptionPane.showMessageDialog(this, "Por favor, selecciona un rol laboral válido.", "Error de validación", JOptionPane.ERROR_MESSAGE);
            return; // Detiene la ejecución
        }

        
        if (!validarEmail(email)) {
            JOptionPane.showMessageDialog(this, "El formato del email no es válido (ej: usuario@dominio.com).", "Email Inválido", JOptionPane.WARNING_MESSAGE);
            return; // Detiene la ejecución
        }
        
        
        if (password.length() < 6) {
            JOptionPane.showMessageDialog(this, "La contraseña debe tener al menos 6 caracteres.", "Contraseña Débil", JOptionPane.WARNING_MESSAGE);
            return; // Detiene la ejecución
        }

        
        gestor.controlador.UsuarioControlador controller = new gestor.controlador.UsuarioControlador();
        
        
        boolean registroExitoso = controller.registrarUsuario(nombre, apellido, email, password, rol);

        
        if (registroExitoso) {
            JOptionPane.showMessageDialog(this, "¡Usuario registrado con éxito!");
            this.dispose(); 
        } else {
            
            JOptionPane.showMessageDialog(this, "Error al registrar: el nombre de usuario o el email ya existen.", "Error de Base de Datos", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_RegistrousuariosActionPerformed

